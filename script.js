async function checkParentingTasks() {
  const u = user();
  let correctCount = 0;
  let totalTasks = 8;

  if (u && !u.reflections) u.reflections = {};

  for (let id = 1; id <= totalTasks; id++) {
    const sel = $(`input[name="taskOpt_${id}"]:checked`);
    const fb = $(`#feedback_${id}`);
    const correctAns = TASK_KEY_ANS[id];

    if (u && sel) {
      u.reflections['task_ans_' + id] = sel.value;
    }

    if (!sel) {
      if (fb) {
        fb.classList.remove('hidden');
        fb.className = 'quiz-feedback unselected';
        fb.textContent = '⚠️ Belum dijawab.';
      }
    } else if (sel.value === correctAns) {
      correctCount++;
      if (fb) {
        fb.classList.remove('hidden');
        fb.className = 'quiz-feedback correct';
        fb.textContent = `✓ Benar! Masuk kategori: ${correctAns}.`;
      }
    } else {
      if (fb) {
        fb.classList.remove('hidden');
        fb.className = 'quiz-feedback wrong';
        fb.textContent = `✕ Kurang tepat. Jawaban resmi modul adalah: ${correctAns}.`;
      }
    }
  }

  const score = Math.round((correctCount / totalTasks) * 100);
  const scoreBox = $('#quizScoreBox');
  if (scoreBox) {
    scoreBox.classList.remove('hidden');
    scoreBox.innerHTML = `
      <h4>Hasil Pemeriksaan: ${score}% (${correctCount} dari ${totalTasks} Benar)</h4>
      <p class="muted">${score === 100 ? '🎉 Sempurna! Anda memahami 4 pilar tugas orang tua secara utuh.' : 'Bagus! Pelajari pembahasan warna di atas untuk memperkuat pemahaman peran orang tua.'}</p>
    `;
  }

  if (u) {
    u.reflections.parenting_quiz_score = score;
    save();
  }
}

