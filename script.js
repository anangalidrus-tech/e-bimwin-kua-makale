function renderModule() {
  const u = user();
  if (!u) { showPage('home'); return; }
  if (!u.progress) u.progress = {};
  [1, 2, 3, 4, 5].forEach(k => {
    if (!Array.isArray(u.progress[k])) u.progress[k] = [];
  });

  const m = modules[activeModule];
  if (!m) return;
  const done = u.progress[activeModule];

  // Update tabs
  $$('.mod-tab').forEach(btn => {
    btn.classList.toggle('active', Number(btn.dataset.switchModule) === activeModule);
  });

  $('#moduleEyebrow').textContent = `MODUL ${activeModule} · ${m.title.toUpperCase()}`;
  $('#moduleNavTitle').textContent = m.title;

  $('#lessonList').innerHTML = m.lessons.map((l, i) => `
    <button class="lesson-link ${i === lessonIndex ? 'active' : ''} ${done.includes(i) ? 'done' : ''}" data-lesson="${i}">
      <span class="lesson-num">${i + 1}</span>
      <span class="lesson-name">${escapeHtml(l[0])}</span>
      ${done.includes(i) ? '<span class="done-check">✓</span>' : ''}
    </button>
  `).join('');

  const pct = Math.round((done.length / m.lessons.length) * 100);
  $('#modulePct').textContent = `${pct}%`;
  $('#moduleBar').style.width = `${pct}%`;

  const lesson = m.lessons[lessonIndex];
  $('#lessonMeta').textContent = `MODUL ${activeModule} · SUBBAB ${lessonIndex + 1} DARI ${m.lessons.length}`;
  $('#lessonTitle').textContent = lesson[0];
  $('#lessonBody').innerHTML = lesson[1];

  // Render the specific interactive tool
  renderLessonActivity(activeModule, lessonIndex);

  $('#prevLesson').disabled = (lessonIndex === 0 && activeModule === 1);
  const isDone = done.includes(lessonIndex);
  const isLastLessonInMod = (lessonIndex === m.lessons.length - 1);

  if (isDone) {
    if (isLastLessonInMod) {
      $('#completeLesson').textContent = (activeModule === 5 ? 'Seluruh Modul Selesai ✓' : `Lanjut ke Modul ${activeModule + 1} →`);
    } else {
      $('#completeLesson').textContent = 'Sudah Selesai · Lanjut →';
    }
  } else {
    $('#completeLesson').textContent = 'Tandai Selesai & Lanjut →';
  }
}

async function completeLesson() {
  const u = user();
  if (!u) return;
  if (!u.progress) u.progress = {};
  if (!Array.isArray(u.progress[activeModule])) u.progress[activeModule] = [];

  const arr = u.progress[activeModule];
  if (!arr.includes(lessonIndex)) arr.push(lessonIndex);

  u.activities.push({
    type: `Modul ${activeModule}: ${modules[activeModule].lessons[lessonIndex][0]} selesai`,
    at: new Date().toISOString()
  });
  save();

  if (sb && u.phone) {
    try {
      sb.from('app_users').update({
        progress: u.progress,
        updated_at: new Date().toISOString()
      }).eq('phone', u.phone).then();
    } catch (e) {}
  }

  const m = modules[activeModule];
  if (lessonIndex < m.lessons.length - 1) {
    lessonIndex++;
    window.scrollTo({ top: 0, behavior: 'smooth' });
    renderModule();
  } else if (activeModule < 5) {
    notify(`✓ Modul ${activeModule} selesai! Melanjutkan ke Modul ${activeModule + 1}.`);
    activeModule++;
    lessonIndex = 0;
    window.scrollTo({ top: 0, behavior: 'smooth' });
    renderModule();
  } else {
    notify('🎉 Selamat! Seluruh 5 Modul Bimwin telah Anda selesaikan. Post-test telah terbuka!');
    renderDashboard();
    showPage('dashboard');
    return;
  }
  renderDashboard();
}

