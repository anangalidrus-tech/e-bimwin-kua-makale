async function syncReflection(key, val) {
  const u = user();
  if (!u) return;
  if (!u.reflections) u.reflections = {};
  u.reflections[key] = val;
  save();

  if (sb && u.phone) {
    try {
      sb.from('app_users').update({
        profile: u.profile,
        progress: u.progress,
        updated_at: new Date().toISOString()
      }).eq('phone', u.phone).then();
    } catch (e) {}
  }
}

// MODUL 1: SUNGAI KEHIDUPAN HANDLERS
function updateRiverCalc() {
  const ageNow = parseInt($('#skAgeNow')?.value || 25, 10);
  const ageMax = parseInt($('#skAgeMax')?.value || 70, 10);
  const diff = Math.max(0, ageMax - ageNow);
  const diffEl = $('#skAgeDiff');
  if (diffEl) diffEl.textContent = `${diff} Tahun`;
  const dispNow = $('#dispAgeNow'), dispMax = $('#dispAgeMax');
  if (dispNow) dispNow.textContent = `${ageNow} th`;
  if (dispMax) dispMax.textContent = `${ageMax} th`;
  const nameTag = $('#riverParticipantTag');
  const u = user();
  if (nameTag) nameTag.textContent = `${(u ? u.name : 'Peserta')} (${diff} tahun)`;
}

async function saveRiverData() {
  const ageNow = $('#skAgeNow')?.value;
  const ageMax = $('#skAgeMax')?.value;
  const akhirat = $('#skAkhirat')?.value;
  const miliki = $('#skMiliki')?.value;
  const lakukan = $('#skLakukan')?.value;
  const prinsip = $('#skPrinsip')?.value;

  const u = user();
  if (!u) return;
  if (!u.reflections) u.reflections = {};
  u.reflections.sk_age_now = ageNow;
  u.reflections.sk_age_max = ageMax;
  u.reflections.sk_akhirat = akhirat;
  u.reflections.sk_miliki = miliki;
  u.reflections.sk_lakukan = lakukan;
  u.reflections.sk_prinsip = prinsip;
  u.activities.push({ type: 'Sungai Kehidupan disimpan', at: new Date().toISOString() });
  save();
  if (sb && u.phone) {
    try {
      sb.from('app_users').update({ updated_at: new Date().toISOString() }).eq('phone', u.phone).then();
    } catch (e) {}
  }
  notify('✓ Sungai Kehidupan berhasil disimpan!');
}

