function renderResults() {
  const u = user();
  if (!u) return;
  const pre = u.pre?.score, post = u.post?.score;
  $('#resultPre').textContent = pre ?? '—';
  $('#resultPost').textContent = post ?? '—';
  $('#resultDelta').textContent = (pre !== undefined && post !== undefined) ? `${post - pre > 0 ? '+' : ''}${post - pre}` : '—';
  $('#preChart').style.width = `${pre ?? 0}%`;
  $('#postChart').style.width = `${post ?? 0}%`;
  $('#preChartLabel').textContent = pre ?? '—';
  $('#postChartLabel').textContent = post ?? '—';

  const totalLessonsDone = [1, 2, 3, 4, 5].reduce((acc, k) => acc + (u.progress[k]?.length || 0), 0);
  const donePct = Math.round((totalLessonsDone / 15) * 100);
  $('#completionNote').textContent = `Penyelesaian 5 Modul: ${donePct}% (${totalLessonsDone}/15 subbab). ${u.post ? 'Post-test telah tuntas diselesaikan.' : 'Selesaikan seluruh 5 modul dan post-test untuk ringkasan akhir.'}`;
}

